#!/bin/sh
# Writes the Homebrew formula for a release, with the published checksums.
#
#   gh release download v0.1.0 --pattern '*.sha256' -D dist
#   scripts/brew-formula.sh 0.1.0 > k9mux.rb
#
# The checksums are read from dist/, so the formula can only ever claim a
# hash that something actually produced. Set BASE_URL to point the formula
# somewhere else - a local dist/ directory, say, to test it before release.
set -eu

version="${1:?usage: scripts/brew-formula.sh <version>}"
repo="${REPO:-nimishgj/k9mux}"
base="${BASE_URL:-https://github.com/$repo/releases/download/v$version}"

# Reads the checksum of one tarball out of the .sha256 file beside it.
sum() {
    file="dist/k9mux-$version-$1.tar.gz.sha256"
    if [ ! -f "$file" ]; then
        echo "missing $file" >&2
        exit 1
    fi
    awk '{print $1}' "$file"
}

block() {
    cat <<EOF
      url "$base/k9mux-$version-$1.tar.gz"
      sha256 "$(sum "$1")"
EOF
}

cat <<EOF
# Generated by scripts/brew-formula.sh - do not edit by hand.
class K9mux < Formula
  desc "Run k9s against several clusters at once"
  homepage "https://github.com/$repo"
  version "$version"
  license "Apache-2.0"

  depends_on "k9s"

  on_macos do
    on_arm do
$(block aarch64-apple-darwin)
    end
    on_intel do
$(block x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
$(block aarch64-unknown-linux-musl)
    end
    on_intel do
$(block x86_64-unknown-linux-musl)
    end
  end

  def install
    bin.install "k9mux"
    # k9mux reads ~/.config/k9mux/config, so the sample is reference
    # material rather than something to install into etc.
    doc.install "README.md", "config.example"
    doc.install Dir["docs/*"]
  end

  test do
    assert_match "k9mux", shell_output("#{bin}/k9mux --help")
    assert_match "set prefix", shell_output("#{bin}/k9mux --keys")
  end
end
EOF
